CREATE TABLE public.inv_stock(
 item_id uuid NOT NULL REFERENCES public.inv_items(id),
 location_id smallint NOT NULL REFERENCES public.inv_locations(id),
 cantidad integer NOT NULL DEFAULT 0 CHECK(cantidad>=0),
 PRIMARY KEY(item_id,location_id)
);
CREATE TABLE public.inv_movements(
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 client_op_id uuid NOT NULL UNIQUE,
 item_id uuid NOT NULL REFERENCES public.inv_items(id),
 tipo text NOT NULL,
 origen smallint,
 destino smallint,
 cantidad integer NOT NULL,
 fecha date NOT NULL,
 vendedor text,
 observaciones text,
 usuario uuid NOT NULL,
 creado_en timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.inv_venta_detalles(
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 venta_id uuid NOT NULL REFERENCES public.inv_ventas(id),
 item_id uuid NOT NULL REFERENCES public.inv_items(id),
 location_id smallint NOT NULL,
 cantidad integer NOT NULL,
 precio_unitario numeric NOT NULL,
 descuento numeric NOT NULL DEFAULT 0,
 subtotal numeric GENERATED ALWAYS AS (cantidad*precio_unitario-descuento) STORED,
 movimiento_id bigint REFERENCES public.inv_movements(id)
);
